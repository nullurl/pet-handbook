# ── 二、通用正则 ──────────────────────────────────────────────────────
REGEX_COMMON = [
    (re.compile(r'原书原文补录（(.+?)）'), r'\1'),
    (re.compile(r'（原文补录）'), ''),
    (re.compile(r'（原文逐条还原）'), '（逐条）'),
    (re.compile(r'（原文数据）'), ''),
    (re.compile(r'原文逐条还原'), '逐条'),
    (re.compile(r'原书原文'), ''),
    # 图注里对来源篇目的引用：**原书《XXX》篇实拍** → **实拍**
    (re.compile(r'原书《[^》]{2,60}》篇(插图|实拍|配图|附录截图|配比图)'), r'\1'),
    (re.compile(r'原书《[^》]{2,60}》篇'), ''),
    (re.compile(r'原书《[^》]{2,60}》'), ''),
    (re.compile(r'原书配图对应的本书插图'), '本书插图'),
    (re.compile(r'《养猫手册 · 十万字全指导（2026版）》'), '内容底本'),
    (re.compile(r'《养猫手册 \| 十万字全指导（2026版）》'), '内容底本'),
    (re.compile(r'《养猫手册》'), '内容底本'),
    (re.compile(r'[ \t]{2,}'), ' '),
]

# ── 三、仅标题适用的清理 ──────────────────────────────────────────────
REGEX_TITLE = [
    (re.compile(r'[（(]\s*[）)]'), ''),
    (re.compile(r'[\s、，,：:；;]+$'), ''),
    (re.compile(r'^[\s、，,：:；;]+'), ''),
]

# ── 四、仅二级小标题（src）适用：去掉序号与篇名 ────────────────────────
REGEX_SUB = [
    (re.compile(r'^[一二三四五六七八九十]+、\s*'), ''),
    (re.compile(r'^[（(][一二三四五六七八九十]+[）)]\s*'), ''),
    (re.compile(r'^\d+[.、]\s*'), ''),
    (re.compile(r'^《[^》]{2,60}》[：:]\s*'), ''),
    (re.compile(r'^《[^》]{2,60}》\s*$'), ''),
    (re.compile(r'^[：:、]\s*'), ''),
]


def nz(s, title=False, sub=False):
    """中性化一段文本。title=True 做标题清理；sub=True 额外去掉序号与篇名。"""
    if not isinstance(s, str):
        return s
    for a, b in RULES:
        if a in s:
            s = s.replace(a, b)
    for pat, rep in REGEX_COMMON:
        s = pat.sub(rep, s)
    if sub:
        for pat, rep in REGEX_SUB:
            s = pat.sub(rep, s)
    if title:
        for pat, rep in REGEX_TITLE:
            s = pat.sub(rep, s)
    return s.strip()
