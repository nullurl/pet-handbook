# 三、附录 F · 内容来源与出处对照
# ══════════════════════════════════════════════════════════════════════
def appendix_sources(kind, chapters, cited):
    """chapters: [(no, title)]；cited: {no: set(rid)}"""
    rows = []
    for no, title in chapters:
        ids = sorted(cited.get(no, set()))
        ref = '、'.join(f'[{i}]' for i in ids) if ids else '—'
        if kind == 'cat':
            name = CAT_SRC.get(no, ('', ''))[0]
            rows.append([f'第 {no} 章 · {title}', f'{name}', ref])
        else:
            rows.append([f'第 {no} 章 · {title}', DOG_SRC.get(no, '本手册独立撰写'), ref])
    head = (['章节', f'内容底本（{BOOK} 对应篇目）', '本章引用的权威来源']
            if kind == 'cat' else
            ['章节', '内容来源', '本章引用的权威来源'])
    lead = (
        f'本手册各章正文由**同一份底本**（{BOOK}，微信公众号「橘南猫舍」25 篇连载）'
        '与**权威来源补充**合并而成。合并后正文不再逐段标注出处，全部对应关系集中列在下面。'
        '表中「引用来源」编号与正文中的 [n] 上标、以及**附录H** 的清单一一对应。'
        if kind == 'cat' else
        '犬篇没有同名底本，各章为本手册独立撰写；写作过程中逐章与猫的常见结论做了比对，'
        '并把疾病、用药、疫苗相关的判断锚定到权威来源。'
        '表中「引用来源」编号与正文中的 [n] 上标、以及**附录H** 的清单一一对应。'
    )
    return [('lead', lead), ('rtable', head, rows)]


